let memoryHistory=null;
function shuffled(items){
 const result=[...items];
 for(let i=result.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[result[i],result[j]]=[result[j],result[i]]}
 return result;
}
function pickWords(count){
 const valid=new Set(WORDS);
 const raw=read(HISTORY_KEY)||memoryHistory||{};
 const history={used:Array.isArray(raw.used)?raw.used.filter(w=>valid.has(w)):[],recent:Array.isArray(raw.recent)?raw.recent.filter(w=>valid.has(w)):[]};
 // Seed the new history from the saved round when upgrading an older installation.
 if(!Array.isArray(raw.used)){
  const previous=read('stroke.round.v1');
  if(Array.isArray(previous?.words)){history.used=previous.words.filter(w=>valid.has(w));history.recent=[...history.used]}
 }
 let used=new Set(history.used);
 const recent=new Set(history.recent.slice(-100)), chosen=[],selected=new Set(),themeCounts=new Map();
 while(chosen.length<count){
  let available=WORD_BANK.filter(entry=>!used.has(entry.word)&&!selected.has(entry.word));
  // Finish the entire unseen deck before starting the next cycle.
  if(!available.length){used=new Set();available=WORD_BANK.filter(entry=>!selected.has(entry.word))}
  if(!available.length)break;
  // At the cycle boundary avoid prompts from the last round whenever possible.
  const notRecent=available.filter(entry=>!recent.has(entry.word));
  if(notRecent.length)available=notRecent;
  const buckets=new Map();
  for(const entry of available){if(!buckets.has(entry.category))buckets.set(entry.category,[]);buckets.get(entry.category).push(entry.word)}
  const minimum=Math.min(...[...buckets.keys()].map(category=>themeCounts.get(category)||0));
  const themes=shuffled([...buckets.keys()].filter(category=>(themeCounts.get(category)||0)===minimum));
  const category=themes[0],options=buckets.get(category),word=options[Math.floor(Math.random()*options.length)];
  chosen.push(word);selected.add(word);used.add(word);themeCounts.set(category,(themeCounts.get(category)||0)+1);
 }
 memoryHistory={used:[...used],recent:[...history.recent,...chosen].slice(-100)};
 store(HISTORY_KEY,memoryHistory);
 return chosen;
}

